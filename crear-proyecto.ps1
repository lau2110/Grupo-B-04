Write-File (Join-Path $pkg "service\ReglasService.java") @(
    'package com.paratytech.cotizaciones.service;'
    ''
    'import org.springframework.stereotype.Service;'
    'import java.math.BigDecimal;'
    'import java.math.RoundingMode;'
    ''
    '@Service'
    'public class ReglasService {'
    ''
    '    public static final String REGLAS_VERSION = "reg-demo-1";'
    '    public static final String TARIFA_VERSION = "tar-demo-1";'
    ''
    '    public BigDecimal precioPorNoche(String habitacionId, String planTarifaId) {'
    '        BigDecimal base = switch (habitacionId.toUpperCase()) {'
    '            case "DOBLE" -> new BigDecimal("2500.00");'
    '            case "SUITE" -> new BigDecimal("4200.00");'
    '            default -> new BigDecimal("1800.00");'
    '        };'
    '        if ("FLEX".equalsIgnoreCase(planTarifaId)) {'
    '            base = base.multiply(new BigDecimal("1.10"));'
    '        }'
    '        return base.setScale(2, RoundingMode.HALF_UP);'
    '    }'
    ''
    '    public BigDecimal impuestos(BigDecimal base, BigDecimal descuento) {'
    '        return base.subtract(descuento)'
    '                .multiply(new BigDecimal("0.16"))'
    '                .setScale(2, RoundingMode.HALF_UP);'
    '    }'
    ''
    '    public BigDecimal cargos() {'
    '        return new BigDecimal("0.00").setScale(2, RoundingMode.HALF_UP);'
    '    }'
    '}'
)

