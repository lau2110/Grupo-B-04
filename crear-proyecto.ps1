Write-File (Join-Path $pkg "service\CotizacionService.java") @(
    'package com.paratytech.cotizaciones.service;'
    ''
    'import com.paratytech.cotizaciones.dto.CotizacionRequest;'
    'import com.paratytech.cotizaciones.dto.CotizacionResponse;'
    'import com.paratytech.cotizaciones.exception.ApiException;'
    'import com.paratytech.cotizaciones.model.Cotizacion;'
    'import com.paratytech.cotizaciones.repository.CotizacionRepository;'
    'import org.springframework.stereotype.Service;'
    'import org.springframework.transaction.annotation.Transactional;'
    ''
    'import java.math.BigDecimal;'
    'import java.math.RoundingMode;'
    'import java.time.LocalDateTime;'
    'import java.time.temporal.ChronoUnit;'
    ''
    '@Service'
    'public class CotizacionService {'
    ''
    '    private final CotizacionRepository repository;'
    '    private final ReglasService reglasService;'
    '    private final FidelizacionService fidelizacionService;'
    ''
    '    public CotizacionService(CotizacionRepository repository,'
    '                             ReglasService reglasService,'
    '                             FidelizacionService fidelizacionService) {'
    '        this.repository = repository;'
    '        this.reglasService = reglasService;'
    '        this.fidelizacionService = fidelizacionService;'
    '    }'
    ''
    '    @Transactional'
    '    public CotizacionResponse crear(CotizacionRequest req, String idempotencyKey) {'
    '        if (idempotencyKey != null && !idempotencyKey.isBlank()) {'
    '            var existente = repository.findByIdempotencyKey(idempotencyKey);'
    '            if (existente.isPresent()) {'
    '                return toResponse(existente.get());'
    '            }'
    '        }'
    ''
    '        if (req.getSalida() == null || req.getEntrada() == null'
    '                || !req.getSalida().isAfter(req.getEntrada())) {'
    '            throw new ApiException(400, "FECHAS_INVALIDAS",'
    '                    "La fecha de salida debe ser posterior a la de entrada");'
    '        }'
    ''
    '        long noches = ChronoUnit.DAYS.between(req.getEntrada(), req.getSalida());'
    '        BigDecimal precioNoche = reglasService.precioPorNoche('
    '                req.getHabitacionId(), req.getPlanTarifaId());'
    '        BigDecimal subtotal = precioNoche'
    '                .multiply(BigDecimal.valueOf(noches))'
    '                .setScale(2, RoundingMode.HALF_UP);'
    ''
    '        BigDecimal descuento = fidelizacionService.descuento('
    '                req.getReferenciaFidelizacion(), subtotal);'
    '        BigDecimal impuestos = reglasService.impuestos(subtotal, descuento);'
    '        BigDecimal total = subtotal.subtract(descuento)'
    '                .add(impuestos)'
    '                .add(reglasService.cargos())'
    '                .setScale(2, RoundingMode.HALF_UP);'
    ''
    '        Cotizacion c = new Cotizacion();'
    '        c.setHotelId(req.getHotelId());'
    '        c.setHabitacionId(req.getHabitacionId());'
    '        c.setEntrada(req.getEntrada());'
    '        c.setSalida(req.getSalida());'
    '        c.setReferenciaFidelizacion(req.getReferenciaFidelizacion());'
    '        c.setSubtotal(subtotal);'
    '        c.setDescuento(descuento);'
    '        c.setImpuestos(impuestos);'
    '        c.setTotal(total);'
    '        c.setEstado("VIGENTE");'
    '        c.setCreadaEn(LocalDateTime.now());'
    '        c.setExpiraEn(LocalDateTime.now().plusMinutes(30));'
    '        c.setIdempotencyKey(idempotencyKey);'
    '        c.setReglasVersion(ReglasService.REGLAS_VERSION);'
    '        c.setTarifaVersion(ReglasService.TARIFA_VERSION);'
    '        c.setBeneficiosVersion(FidelizacionService.BENEFICIOS_VERSION);'
    ''
    '        return toResponse(repository.save(c));'
    '    }'
    ''
    '    @Transactional(readOnly = true)'
    '    public CotizacionResponse consultar(Long id) {'
    '        Cotizacion c = repository.findById(id)'
    '                .orElseThrow(() -> new ApiException(404, "NO_ENCONTRADA",'
    '                        "Cotizacion no encontrada: " + id));'
    '        return toResponse(c);'
    '    }'
    ''
    '    @Transactional'
    '    public CotizacionResponse decidir(Long id, String decision) {'
    '        Cotizacion c = repository.findById(id)'
    '                .orElseThrow(() -> new ApiException(404, "NO_ENCONTRADA",'
    '                        "Cotizacion no encontrada: " + id));'
    ''
    '        if (c.getExpiraEn() != null && c.getExpiraEn().isBefore(LocalDateTime.now())) {'
    '            c.setEstado("VENCIDA");'
    '            repository.save(c);'
    '            throw new ApiException(409, "COTIZACION_VENCIDA",'
    '                    "La cotizacion ya expiro y no puede modificarse");'
    '        }'
    ''
    '        if (!"ACEPTAR".equalsIgnoreCase(decision)'
    '                && !"RECHAZAR".equalsIgnoreCase(decision)) {'
    '            throw new ApiException(400, "DECISION_INVALIDA",'
    '                    "La decision debe ser ACEPTAR o RECHAZAR");'
    '        }'
    ''
    '        c.setEstado("ACEPTAR".equalsIgnoreCase(decision) ? "ACEPTADA" : "RECHAZADA");'
    '        return toResponse(repository.save(c));'
    '    }'
    ''
    '    private CotizacionResponse toResponse(Cotizacion c) {'
    '        CotizacionResponse r = new CotizacionResponse();'
    '        r.setId(c.getId());'
    '        r.setHotelId(c.getHotelId());'
    '        r.setHabitacionId(c.getHabitacionId());'
    '        r.setEntrada(c.getEntrada());'
    '        r.setSalida(c.getSalida());'
    '        r.setSubtotal(c.getSubtotal());'
    '        r.setDescuento(c.getDescuento());'
    '        r.setImpuestos(c.getImpuestos());'
    '        r.setTotal(c.getTotal());'
    '        r.setEstado(c.getEstado());'
    '        r.setCreadaEn(c.getCreadaEn());'
    '        r.setExpiraEn(c.getExpiraEn());'
    '        r.setReglasVersion(c.getReglasVersion());'
    '        r.setTarifaVersion(c.getTarifaVersion());'
    '        r.setBeneficiosVersion(c.getBeneficiosVersion());'
    '        return r;'
    '    }'
    '}'
)

